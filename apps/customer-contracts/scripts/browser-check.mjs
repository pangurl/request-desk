import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import {createApp} from '../server/app.mjs'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright')
const {app,close}=createApp(),server=app.listen(0,'127.0.0.1')
await new Promise(resolve=>server.once('listening',resolve))
const base='http://127.0.0.1:'+server.address().port
let browser
try{
 browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),args:['--no-sandbox']})
 const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage(),errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto(base)
 await page.getByPlaceholder('请输入账号').fill('admin')
 await page.getByPlaceholder('请输入密码').fill('LocalDemo2026!')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await page.getByRole('heading',{name:'业务概览'}).waitFor()
 await page.getByRole('menuitem',{name:'客户档案'}).click()
 await page.getByRole('button',{name:'新增客户'}).click()
 let dialog=page.getByRole('dialog')
 let inputs=dialog.locator('input')
 await inputs.nth(0).fill('浏览器验证客户')
 await inputs.nth(1).fill('王经理')
 await inputs.nth(3).fill('wang@example.com')
 await dialog.getByRole('button',{name:'保存客户'}).click()
 await page.getByRole('button',{name:'浏览器验证客户',exact:true}).waitFor()
 await page.getByRole('menuitem',{name:'合同管理'}).click()
 await page.getByRole('button',{name:'新建合同',exact:true}).click()
 dialog=page.getByRole('dialog')
 await dialog.locator('input').nth(0).fill('年度技术服务合同')
 await dialog.locator('.el-select').click()
 await page.getByRole('option',{name:'浏览器验证客户'}).click()
 await dialog.getByPlaceholder('如 12000.00').fill('12000.35')
 await dialog.getByPlaceholder('选择开始日期').fill('2026-01-01')
 await dialog.getByPlaceholder('选择开始日期').press('Enter')
 await dialog.getByPlaceholder('选择结束日期').fill('2026-12-31')
 await dialog.getByPlaceholder('选择结束日期').press('Enter')
 await dialog.getByRole('button',{name:'保存草稿'}).click()
 let drawer=page.getByRole('dialog')
 await drawer.getByRole('heading',{name:'年度技术服务合同'}).waitFor()
 await drawer.getByRole('button',{name:'提交审核',exact:true}).click()
 dialog=page.getByRole('dialog').last()
 await dialog.getByRole('button',{name:'确认提交审核'}).click()
 await page.locator('.el-drawer').getByText('待审核',{exact:true}).waitFor()
 await page.locator('.el-drawer__close-btn').click()
 await page.locator('.filters .el-select').first().click()
 await page.getByRole('option',{name:'待审核',exact:true}).click()
 await page.getByRole('button',{name:'查询',exact:true}).click()
 await page.getByRole('button',{name:'年度技术服务合同',exact:true}).click()
 await page.locator('.el-drawer').getByRole('button',{name:'审核通过',exact:true}).click()
 await page.getByRole('dialog').last().getByRole('button',{name:'确认审核通过'}).click()
 await page.locator('.el-drawer').getByText('已生效',{exact:true}).waitFor()
 await page.locator('.el-table__empty-text').getByText('暂无匹配合同',{exact:false}).waitFor()
 console.log('PASS: 客户创建 → 合同草稿 → 提交 → 审核；待审列表与详情同步')
 await page.locator('.el-drawer__close-btn').click()
 // A real server revision arrives while an existing edit form remains open.
 const customer=(await (await context.request.get(base+'/api/customer-options')).json()).find(c=>c.name==='浏览器验证客户')
 const payload={title:'并发校验合同',customer_id:customer.id,amount_cents:10000,start_date:'2026-01-01',end_date:'2026-12-31'}
 const record=await(await context.request.post(base+'/api/contracts',{data:payload})).json()
 await page.getByRole('button',{name:'重置',exact:true}).click()
 const row=page.getByRole('row').filter({hasText:'并发校验合同'})
 await row.getByRole('button',{name:'编辑',exact:true}).click()
 dialog=page.getByRole('dialog')
 await dialog.locator('input').nth(0).fill('我的未保存修改')
 assert.equal((await context.request.put(base+'/api/contracts/'+record.id,{data:{...payload,version:record.version,title:'其他成员的新标题'}})).status(),200)
 await dialog.getByRole('button',{name:'保存草稿'}).click()
 await dialog.getByText('合同已更新，当前输入已保留。请先核对服务器版本。',{exact:true}).waitFor()
 assert.equal(await dialog.locator('input').nth(0).inputValue(),'我的未保存修改')
 assert.equal(await dialog.getByRole('button',{name:'保存草稿'}).isDisabled(),true)
 console.log('PASS: 真实409冲突保留表单输入，禁用旧版本提交')
 await dialog.getByRole('button',{name:'取消',exact:true}).click()
 await page.getByRole('menuitem',{name:'业务概览'}).click()
 await page.getByRole('heading',{name:'业务概览'}).waitFor()
 await page.locator('.el-message').first().waitFor({state:'detached'}).catch(()=>{})
 await page.waitForTimeout(500)
 if(process.env.SCREENSHOT_PATH)await page.screenshot({path:process.env.SCREENSHOT_PATH,fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await page.waitForTimeout(200)
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 assert.deepEqual(errors,[])
 console.log('PASS: 390px布局无页面横向溢出；页面无未捕获JavaScript错误')
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));close()}
